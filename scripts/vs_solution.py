"""Writes GWToolbox.slnx at the repo root for Visual Studio (and Rider): one Makefile project per CMake target in
build/Windows/relwithdebinfo/compile_commands.json, in .vs-projects/. Building runs scripts/build.py, so Visual Studio builds with
llvm-mingw exactly as CLion and the terminal do. Debug, RelWithDebInfo and Release are the debug, relwithdebinfo and
release presets.

The Windows bootstrap runs it; run it again after adding or removing source files:

    python scripts/vs_solution.py

IntelliSense gets each target's include paths, defines and precompiled header, but keeps Visual Studio's own standard
library and Windows SDK headers: it has no GNU clang mode for these projects and misreads libc++. Code under
__MINGW32__ therefore shows as inactive.
"""

import require_python  # noqa: F401  (first: stops an old Python before anything else runs)

import hashlib
import json
import ntpath
import os
import re
import shutil
import sys
import uuid

from common import PRESET_BUILD_DIRS, PRESETS, REPO_ROOT, TOOLCHAIN_DIR, Failure, main_guard

LAUNCHER = "GWToolbox"
HEADER_EXTENSIONS = (".h", ".hpp", ".inl")
CONFIGURATIONS = {PRESETS[preset]: preset for preset in ("debug", "relwithdebinfo", "release")}
GENERATED = "<!-- Generated by scripts\\vs_solution.py; changes are lost when it runs again. -->"


def split_command_line(line):
    # Quoted runs keep their spaces, and \" is a literal quote: CMake writes defines such as -DVERSION=\"8.35\".
    parts, current, quoted, started = [], [], False, False
    i = 0
    while i < len(line):
        c = line[i]
        if c == "\\" and i + 1 < len(line) and line[i + 1] == '"':
            current.append('"')
            started = True
            i += 2
            continue
        if c == '"':
            quoted, started = not quoted, True
        elif c.isspace() and not quoted:
            if started:
                parts.append("".join(current))
                current, started = [], False
        else:
            current.append(c)
            started = True
        i += 1
    if started:
        parts.append("".join(current))
    return parts


def full_path(path, directory):
    return os.path.normpath(path if os.path.isabs(path) else os.path.join(directory, path))


def starts_with(path, folder):
    return os.path.normcase(path).startswith(os.path.normcase(folder.rstrip("\\/") + os.sep))


def relative_path(start, path):
    return os.path.relpath(path, start).replace("/", "\\")


def stable_guid(name):
    # The same GUID for the same name on every run, so regenerating keeps Visual Studio's per-project settings.
    return "{%s}" % str(uuid.UUID(bytes_le=hashlib.md5(name.encode("utf-8")).digest())).upper()


def escape(text):
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
            .replace("'", "&apos;"))


def read_targets(database, build_dir):
    with open(database, encoding="utf-8") as file:
        entries = json.load(file)
    dependencies = os.path.join(REPO_ROOT, "Dependencies")
    targets = {}
    for entry in entries:
        source = full_path(entry["file"], entry["directory"])
        # Sources fetched or generated into the build folder belong to third-party targets, which get no project.
        if starts_with(source, build_dir) or starts_with(source, dependencies):
            continue
        arguments = entry.get("arguments") or split_command_line(entry["command"])
        if "-o" not in arguments:
            continue
        match = re.search(r"CMakeFiles[\\/]([^\\/]+)\.dir[\\/]", arguments[arguments.index("-o") + 1])
        if not match:
            continue
        target = targets.setdefault(match.group(1), {"sources": [], "arguments": arguments, "directory": entry["directory"]})
        target["sources"].append(source)
    return targets


def compiler_settings(target):
    includes, defines, forced = [], [], []
    a = target["arguments"]
    i = 1
    while i < len(a):
        arg, path = a[i], None
        if arg in ("-I", "-isystem"):
            i += 1
            path = a[i]
        elif arg.startswith("-I"):
            path = arg[2:]
        elif arg.startswith("-D"):
            defines.append(arg[2:])
        elif arg == "-include":
            i += 1
            forced.append(full_path(a[i], target["directory"]))
        elif arg == "-Xclang" and i + 3 < len(a) and a[i + 1] == "-include":
            forced.append(full_path(a[i + 3], target["directory"]))
            i += 3
        if path:
            path = full_path(path, target["directory"])
            # llvm-mingw's own headers are left out; see the note at the top.
            if not starts_with(path, TOOLCHAIN_DIR) and path not in includes:
                includes.append(path)
        i += 1
    return includes, defines, forced


def project_files(target):
    sources = target["sources"]
    root = os.path.dirname(sources[0])
    for source in sources:
        while not starts_with(source, root):
            root = os.path.dirname(root)
    if os.path.normcase(root) == os.path.normcase(REPO_ROOT):
        # A target spanning top-level folders would otherwise take in the whole checkout, build and toolchain folders too.
        candidates = [os.path.join(directory, name) for directory in sorted(set(map(os.path.dirname, sources)), key=str.lower)
                      for name in sorted(os.listdir(directory), key=str.lower) if os.path.isfile(os.path.join(directory, name))]
    else:
        candidates = [os.path.join(directory, name) for directory, _, names in sorted(os.walk(root), key=lambda w: w[0].lower())
                      for name in sorted(names, key=str.lower)]
    headers = [path for path in candidates if path.lower().endswith(HEADER_EXTENSIONS)]
    return root, [("ClCompile", path) for path in sources] + [("ClInclude", path) for path in headers]


def write_project(name, target, project_dir, python):
    includes, defines, forced = compiler_settings(target)
    root, files = project_files(target)
    build_script = "$(MSBuildProjectDirectory)\\..\\scripts\\build.py"
    output = "GWToolbox.exe" if name == LAUNCHER else name + ".dll"
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        GENERATED,
        '<Project DefaultTargets="Build" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">',
        '  <ItemGroup Label="ProjectConfigurations">',
    ]
    for config in CONFIGURATIONS:
        lines.append('    <ProjectConfiguration Include="%s|Win32"><Configuration>%s</Configuration><Platform>Win32</Platform>'
                     '</ProjectConfiguration>' % (config, config))
    lines += [
        '  </ItemGroup>',
        '  <PropertyGroup Label="Globals"><ProjectGuid>%s</ProjectGuid><Keyword>MakeFileProj</Keyword><ProjectName>%s'
        '</ProjectName></PropertyGroup>' % (stable_guid(name), name),
        '  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.Default.props" />',
        '  <PropertyGroup Label="Configuration"><ConfigurationType>Makefile</ConfigurationType><PlatformToolset>'
        '$(DefaultPlatformToolset)</PlatformToolset></PropertyGroup>',
        '  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.props" />',
    ]
    for config, preset in CONFIGURATIONS.items():
        build = '"%s" "%s" --preset %s --msvc-diagnostics' % (python, build_script, preset)
        lines += [
            "  <PropertyGroup Condition=\"'$(Configuration)'=='%s'\">" % config,
            "    <NMakeBuildCommandLine>%s</NMakeBuildCommandLine>" % escape("%s --target %s" % (build, name)),
            "    <NMakeReBuildCommandLine>%s</NMakeReBuildCommandLine>" % escape("%s --rebuild --target %s" % (build, name)),
            "    <NMakeCleanCommandLine>%s</NMakeCleanCommandLine>" % escape("%s --clean --target %s" % (build, name)),
            "    <NMakeOutput>$(MSBuildProjectDirectory)\\..\\bin\\%s\\%s</NMakeOutput>" % (config, output),
            "    <NMakePreprocessorDefinitions>%s</NMakePreprocessorDefinitions>" % escape(";".join(defines + ["$(NMakePreprocessorDefinitions)"])),
            "    <NMakeIncludeSearchPath>%s</NMakeIncludeSearchPath>" % escape(";".join(includes + ["$(IncludePath)"])),
            "    <NMakeForcedIncludes>%s</NMakeForcedIncludes>" % escape(";".join(forced)),
            "    <AdditionalOptions>/std:c++latest</AdditionalOptions>",
            "    <OutDir>$(MSBuildProjectDirectory)\\obj\\%s\\%s\\</OutDir><IntDir>$(MSBuildProjectDirectory)\\obj\\%s\\%s\\</IntDir>"
            % (name, config, name, config),
            # Every project starts the launcher with /localdll, which injects the GWToolboxdll.dll next to it.
            "    <DebuggerFlavor>WindowsLocalDebugger</DebuggerFlavor>",
            "    <LocalDebuggerCommand>$(MSBuildProjectDirectory)\\..\\bin\\%s\\GWToolbox.exe</LocalDebuggerCommand>" % config,
            "    <LocalDebuggerCommandArguments>/localdll</LocalDebuggerCommandArguments>",
            "    <LocalDebuggerWorkingDirectory>$(MSBuildProjectDirectory)\\..\\bin\\%s\\</LocalDebuggerWorkingDirectory>" % config,
            "  </PropertyGroup>",
        ]
    lines.append("  <ItemGroup>")
    lines += ['    <%s Include="%s" />' % (kind, escape(relative_path(project_dir, path))) for kind, path in files]
    lines += ["  </ItemGroup>", '  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.targets" />', "</Project>"]
    write_text(os.path.join(project_dir, name + ".vcxproj"), lines)

    # Solution Explorer shows the files in their folders, relative to the shared root.
    folders = set()
    filters = ['<?xml version="1.0" encoding="utf-8"?>',
               '<Project ToolsVersion="4.0" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">', "  <ItemGroup>"]
    for kind, path in files:
        folder = os.path.dirname(relative_path(root, path))
        item = '    <%s Include="%s"' % (kind, escape(relative_path(project_dir, path)))
        if folder:
            filters.append("%s><Filter>%s</Filter></%s>" % (item, escape(folder), kind))
            while folder:
                folders.add(folder)
                folder = ntpath.dirname(folder)
        else:
            filters.append(item + " />")
    for folder in sorted(folders, key=str.lower):
        filters.append('    <Filter Include="%s"><UniqueIdentifier>%s</UniqueIdentifier></Filter>'
                       % (escape(folder), stable_guid("%s/%s" % (name, folder))))
    filters += ["  </ItemGroup>", "</Project>"]
    write_text(os.path.join(project_dir, name + ".vcxproj.filters"), filters)


def write_text(path, lines):
    with open(path, "w", encoding="utf-8", newline="\r\n") as file:
        file.write("\n".join(lines) + "\n")


def write_solution():
    build_dir = os.path.join(REPO_ROOT, PRESET_BUILD_DIRS["relwithdebinfo"])
    database = os.path.join(build_dir, "compile_commands.json")
    if not os.path.isfile(database):
        raise Failure("%s not found; configure the relwithdebinfo preset first (the bootstrap does)" % database)
    targets = read_targets(database, build_dir)
    if not targets:
        raise Failure("no GWToolbox targets found in " + database)
    project_dir = os.path.join(REPO_ROOT, ".vs-projects")
    os.makedirs(project_dir, exist_ok=True)
    # Where earlier versions wrote the projects; it only ever held generated files.
    shutil.rmtree(os.path.join(REPO_ROOT, ".vs-mingw"), ignore_errors=True)
    # The interpreter running this, so the projects build with a Python that has been seen to work.
    python = sys.executable
    for name, target in targets.items():
        write_project(name, target, project_dir, python)

    # Ninja orders the targets itself and build.py makes runs in one build folder take turns, so the only
    # dependency is GWToolboxdll's on the launcher its debugger starts. Listed first, GWToolboxdll is the startup project.
    names = sorted(targets, key=lambda n: (0 if n == "GWToolboxdll" else 1 if n == LAUNCHER else 2, n.lower()))
    dependencies = {"GWToolboxdll": [LAUNCHER]}
    solution = [GENERATED, "<Solution>", "  <Configurations>"]
    solution += ['    <BuildType Name="%s" />' % config for config in CONFIGURATIONS]
    solution += ['    <Platform Name="Win32" />', "  </Configurations>"]
    for name in names:
        needs = [need for need in dependencies.get(name, []) if need in targets]
        if not needs:
            solution.append('  <Project Path=".vs-projects/%s.vcxproj" />' % name)
        else:
            solution.append('  <Project Path=".vs-projects/%s.vcxproj">' % name)
            solution += ['    <BuildDependency Project=".vs-projects/%s.vcxproj" />' % need for need in needs]
            solution.append("  </Project>")
    solution.append("</Solution>")
    write_text(os.path.join(REPO_ROOT, "GWToolbox.slnx"), solution)
    return names


def main():
    names = write_solution()
    print("wrote GWToolbox.slnx with %d projects: %s" % (len(names), ", ".join(names)))


if __name__ == "__main__":
    main_guard(main)
